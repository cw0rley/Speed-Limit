// Generates US-style speed-limit sign PNGs (white rounded rectangle, black
// border, "SPEED LIMIT" label + big number) for use as CarPlay Grid tile
// images. CarPlay only lets us drop images into templates — it can't draw the
// app's custom UI — so the sign that looks like the phone app has to be a
// pre-rendered image with the number baked in.
//
// Real posted speed limits are multiples of 5, so we render 5..130 step 5 plus
// an "unknown" (--) sign. At runtime App.js snaps the current limit to the
// nearest available sign.
//
// Run: node generate-signs.js   (writes assets/signs/*.png and signAssets.js)

const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

// Top-level folder (NOT under assets/) so .easignore's `assets/*` allow-list
// doesn't strip these from the EAS upload — Metro require()s them at runtime.
const outDir = path.join(__dirname, 'carplay-signs');
fs.mkdirSync(outDir, { recursive: true });

// Portrait US speed-limit sign. Rendered large; CarPlay downscales to the tile.
function signSvg(label) {
  const big = label.length >= 3 ? 150 : 200; // shrink font for "--"/3-digit
  return `<svg xmlns="http://www.w3.org/2000/svg" width="330" height="420" viewBox="0 0 330 420">
  <rect x="12" y="12" width="306" height="396" rx="28" ry="28" fill="#ffffff" stroke="#000000" stroke-width="16"/>
  <text x="165" y="95" font-family="Arial, Helvetica, sans-serif" font-size="54" font-weight="700" text-anchor="middle" fill="#000000" letter-spacing="2">SPEED</text>
  <text x="165" y="158" font-family="Arial, Helvetica, sans-serif" font-size="54" font-weight="700" text-anchor="middle" fill="#000000" letter-spacing="2">LIMIT</text>
  <text x="165" y="350" font-family="Arial, Helvetica, sans-serif" font-size="${big}" font-weight="800" text-anchor="middle" fill="#000000">${label}</text>
</svg>`;
}

const values = [];
for (let v = 5; v <= 130; v += 5) values.push(v);

async function generate() {
  const entries = [];
  for (const v of values) {
    await sharp(Buffer.from(signSvg(String(v))))
      .png()
      .toFile(path.join(outDir, `${v}.png`));
    entries.push(`  ${v}: require('./carplay-signs/${v}.png'),`);
  }
  await sharp(Buffer.from(signSvg('--')))
    .png()
    .toFile(path.join(outDir, 'unknown.png'));

  const module = `// AUTO-GENERATED by generate-signs.js — do not edit by hand.
export const SIGN_IMAGES = {
${entries.join('\n')}
};
export const SIGN_UNKNOWN = require('./carplay-signs/unknown.png');
`;
  fs.writeFileSync(path.join(__dirname, 'signAssets.js'), module);
  console.log(`Generated ${values.length} signs + unknown, and signAssets.js`);
}

generate().catch((e) => {
  console.error('Error:', e);
  process.exit(1);
});
